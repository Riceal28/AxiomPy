"""Generate ``axiom/core/containers_data.py`` from the original container sources.

Two things are extracted:

* ``Controls/FormatContainers.cs`` - the per-container item lists (media types and the
  codecs each container accepts) as ``CONTAINERS``,
* ``Controls/FormatControls.cs`` - the "container selected" switch, which is a flat run of
  ``VM.<View>.<Field> = Containers.<Class>.<list>;`` / literal assignments, as
  ``FORMAT_CONTROLS``.

Usage:
    python tools/codegen/gen_containers.py [--src PATH] [--out PATH]
"""

from __future__ import annotations

import argparse
import pprint
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULT_SRC = Path(r"G:\Codex_workspace\Axiom\source\Axiom\Axiom")
DEFAULT_OUT = HERE.parent.parent / "src" / "axiom" / "core" / "containers_data.py"

CONTAINER_CLASS = re.compile(r"public\s+class\s+(?P<name>\w+)", re.MULTILINE)
CONTAINER_LIST = re.compile(
    r"public\s+readonly\s+static\s+ObservableCollection<string>\s+(?P<name>\w+)\s*=\s*"
    r"new\s+ObservableCollection<string>\(\)\s*\{",
    re.MULTILINE,
)
FORMAT_CASE = re.compile(r'case\s+"(?P<container>[^"]+)"\s*:')
LIST_ASSIGN = re.compile(
    r"VM\.(?P<view>\w+)View\.(?P<field>\w+)\s*=\s*Containers\.(?P<cls>\w+)\.(?P<list>\w+)\s*;"
)
VALUE_ASSIGN = re.compile(r'VM\.(?P<view>\w+)View\.(?P<field>\w+)\s*=\s*(?P<value>[^;]+);')
STRING = re.compile(r'@?"((?:[^"\\]|\\.)*)"')


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8-sig", errors="replace")


def match_brace(text: str, open_index: int) -> int:
    depth = 0
    for index in range(open_index, len(text)):
        char = text[index]
        if char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                return index
    return len(text) - 1


def parse_containers(text: str) -> dict:
    containers: dict = {}
    outer_end = match_brace(text, text.find("{", CONTAINER_CLASS.search(text).end()))
    for cls in CONTAINER_CLASS.finditer(text):
        if cls.start() > outer_end:
            break
        if cls.group("name") == "Containers":
            continue
        end = match_brace(text, text.find("{", cls.end()))
        body = text[cls.end() : end]
        lists: dict = {}
        for item in CONTAINER_LIST.finditer(body):
            list_end = match_brace(body, item.end() - 1)
            lists[item.group("name")] = [
                literal.replace('\\"', '"') for literal in STRING.findall(body[item.end() : list_end])
            ]
        if lists:
            containers[cls.group("name")] = lists
    return containers


def parse_format_controls(text: str) -> dict:
    start = text.find("FormatControls(string container_SelectedItem)")
    if start < 0:
        return {}
    body = text[start : match_brace(text, text.find("{", start))]
    cases = [(match.group("container"), match.end()) for match in FORMAT_CASE.finditer(body)]
    table: dict = {}
    for index, (container, case_start) in enumerate(cases):
        if index + 1 < len(cases):
            next_match = FORMAT_CASE.finditer(body)
            offsets = [m.start() for m in next_match]
            end = offsets[index + 1] if index + 1 < len(offsets) else len(body)
        else:
            end = len(body)
        segment = body[case_start:end]
        assignments: dict = {}
        for match in LIST_ASSIGN.finditer(segment):
            assignments[match.group("view") + "." + match.group("field")] = [
                "list",
                match.group("cls"),
                match.group("list"),
            ]
        for match in VALUE_ASSIGN.finditer(segment):
            key = match.group("view") + "." + match.group("field")
            if key in assignments:
                continue
            raw = match.group("value").strip()
            literal = re.fullmatch(r'@?"(.*)"', raw, re.DOTALL)
            if literal:
                assignments[key] = ["value", literal.group(1)]
            elif raw in ("true", "false"):
                assignments[key] = ["value", raw == "true"]
        if assignments:
            table[container] = assignments
    return table


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--src", default=str(DEFAULT_SRC))
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    args = parser.parse_args()
    src = Path(args.src)

    containers = parse_containers(read(src / "Controls/FormatContainers.cs"))
    format_controls = parse_format_controls(read(src / "Controls/FormatControls.cs"))

    header = [
        '"""Generated by tools/codegen/gen_containers.py - do not edit by hand.',
        "",
        "``CONTAINERS``: per-container item lists (media type, video/audio/subtitle codecs).",
        "``FORMAT_CONTROLS``: what selecting a container installs into the view models -",
        "list references (``[\"list\", class, list]``) and literal defaults.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "CONTAINERS: dict = ",
    ]
    text = "\n".join(header) + pprint.pformat(containers, width=110, sort_dicts=False)
    text += "\n\nFORMAT_CONTROLS: dict = "
    text += pprint.pformat(format_controls, width=110, sort_dicts=False) + "\n"
    Path(args.out).write_text(text, encoding="utf-8")
    print(f"containers={len(containers)} format_cases={len(format_controls)} -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
